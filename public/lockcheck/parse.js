/* AXM Lockcheck: lectura de archivos de dependencias. Todo ocurre en el navegador. */
(function () {
  'use strict'

  /* package-lock.json (v1, v2 y v3) */
  function npmLock(text) {
    const j = JSON.parse(text)
    const out = []
    const direct = new Set()
    if (j.packages) {
      const root = j.packages[''] || {}
      for (const k of ['dependencies', 'devDependencies', 'optionalDependencies']) Object.keys(root[k] || {}).forEach((n) => direct.add(n))
      for (const [path, p] of Object.entries(j.packages)) {
        if (!path || p.link) continue
        const name = p.name || path.slice(path.lastIndexOf('node_modules/') + 13)
        if (!p.version) continue
        out.push({ eco: 'npm', name, version: p.version, resolved: p.resolved || '', integrity: p.integrity || '', script: !!p.hasInstallScript, dev: !!p.dev, direct: direct.has(name) && path === `node_modules/${name}` })
      }
    } else if (j.dependencies) {
      Object.keys(j.dependencies).forEach((n) => direct.add(n))
      const walk = (deps, top) => {
        for (const [name, p] of Object.entries(deps || {})) {
          out.push({ eco: 'npm', name, version: p.version, resolved: p.resolved || '', integrity: p.integrity || '', script: false, dev: !!p.dev, direct: top && direct.has(name) })
          walk(p.dependencies, false)
        }
      }
      walk(j.dependencies, true)
    }
    return out
  }

  /* yarn.lock clásico (v1) y moderno (berry) */
  function yarnLock(text) {
    const out = []
    const blocks = text.split(/\n(?=\S)/)
    for (const b of blocks) {
      const lines = b.split('\n')
      const head = lines[0]
      if (!head || head.startsWith('#') || head.startsWith('__metadata')) continue
      const spec = head.replace(/:$/, '').split(',')[0].trim().replace(/^"|"$/g, '')
      const at = spec.lastIndexOf('@')
      if (at <= 0) continue
      const name = spec.slice(0, at)
      const v = b.match(/\n\s+version:?\s+"?([^"\n]+)"?/)
      if (!v) continue
      const res = b.match(/\n\s+(?:resolved|resolution):?\s+"?([^"\n]+)"?/)
      const integ = b.match(/\n\s+(?:integrity|checksum):?\s+"?([^"\n]+)"?/)
      out.push({ eco: 'npm', name, version: v[1], resolved: res ? res[1] : '', integrity: integ ? integ[1] : '', script: false, dev: false, direct: false })
    }
    return out
  }

  /* pnpm-lock.yaml (v5, v6 y v9) */
  function pnpmLock(text) {
    const out = []
    const sec = text.split(/\n(?=\S)/).find((s) => s.startsWith('packages:'))
    if (!sec) return out
    for (const m of sec.matchAll(/\n {2}'?\/?((?:@[^/@\s]+\/)?[^/@\s(]+)[@/]([0-9][^:('\s]*)/g)) {
      out.push({ eco: 'npm', name: m[1], version: m[2], resolved: '', integrity: 'pnpm', script: false, dev: false, direct: false })
    }
    return out
  }

  /* requirements.txt (solo versiones fijadas con ==) */
  function pipReq(text) {
    const out = []
    for (const raw of text.split('\n')) {
      const line = raw.split('#')[0].trim()
      const m = line.match(/^([A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^\]]*\])?\s*==\s*([^\s;]+)/)
      if (m) out.push({ eco: 'PyPI', name: m[1].toLowerCase(), version: m[2], resolved: '', integrity: /--hash=/.test(raw) ? 'hash' : '', script: false, dev: false, direct: true })
    }
    return out
  }

  function detect(name, text) {
    const n = (name || '').toLowerCase()
    const t = text.trimStart()
    if (n.endsWith('package-lock.json') || n.endsWith('npm-shrinkwrap.json') || (t.startsWith('{') && /"lockfileVersion"/.test(t))) return ['package-lock.json', npmLock(text)]
    if (n.endsWith('yarn.lock') || /^# (THIS IS AN AUTOGENERATED FILE|yarn lockfile)|__metadata:/m.test(t)) return ['yarn.lock', yarnLock(text)]
    if (n.endsWith('pnpm-lock.yaml') || /^lockfileVersion:/m.test(t)) return ['pnpm-lock.yaml', pnpmLock(text)]
    if (n.endsWith('.txt') || /^[A-Za-z0-9._-]+\s*==/m.test(t)) return ['requirements.txt', pipReq(text)]
    if (n.endsWith('package.json') || /"dependencies"\s*:/.test(t)) throw new Error('package.json')
    throw new Error('unknown')
  }

  function dedupe(list) {
    const map = new Map()
    for (const p of list) {
      const k = `${p.eco}|${p.name}|${p.version}`
      const prev = map.get(k)
      if (!prev) map.set(k, { ...p })
      else { prev.script ||= p.script; prev.direct ||= p.direct; prev.dev &&= p.dev }
    }
    return [...map.values()]
  }

  window.Lock = { detect, dedupe }
})()
